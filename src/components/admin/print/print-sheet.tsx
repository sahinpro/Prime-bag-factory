import Image from "next/image";
import * as React from "react";

import { PrintToolbar } from "@/components/admin/print/print-toolbar";
import type { CompanyProfile } from "@/server/settings";

/**
 * PrintSheet (plan 9c.5): the A4 print layout shared by the quote production
 * spec sheet and quotation (and later the invoice / packing slip). Black on
 * white in both themes, logo on light, no admin chrome (these pages render
 * outside the shell), `@page` rules in globals.css, sections avoid page-break
 * splits. On screen it is a plain document page with a Print button.
 *
 * The white/black here is the plan's explicit print spec ("black on white"),
 * not a theme color — screen tokens must not leak ink/gold into printed output.
 */
export function PrintSheet({
  documentTitle,
  documentNumber,
  issuedOn,
  company,
  children,
}: Readonly<{
  documentTitle: string;
  documentNumber: string;
  issuedOn: string;
  company: CompanyProfile;
  children: React.ReactNode;
}>) {
  return (
    <main id="main" className="min-h-screen bg-surface-2 py-8 print:bg-white print:py-0">
      <PrintToolbar documentTitle={documentTitle} />
      <article
        aria-label={documentTitle}
        className="mx-auto w-full max-w-[210mm] bg-white px-6 py-8 text-black shadow-lg sm:px-[16mm] sm:py-[14mm] print:max-w-none print:px-0 print:py-0 print:shadow-none"
      >
        <header className="flex items-start justify-between gap-6 border-b-2 border-black pb-4">
          <div className="flex items-center gap-3">
            <Image
              src="/brand/logo-mark.svg"
              alt=""
              width={44}
              height={44}
              className="size-11"
            />
            <div>
              <p className="text-lg font-semibold leading-tight">
                {company.name}
              </p>
              <p className="text-xs text-black/70">
                {[company.phone, company.email]
                  .filter(Boolean)
                  .join(" · ")}
              </p>
            </div>
          </div>
          <div className="text-right">
            <h1 className="text-base font-semibold uppercase tracking-wide">
              {documentTitle}
            </h1>
            <p className="text-xs text-black/70">
              No. {documentNumber} · Issued {issuedOn}
            </p>
          </div>
        </header>

        <div className="mt-6 space-y-6">{children}</div>

        <footer className="mt-10 border-t border-black pt-3 text-[10px] text-black/70">
          Generated by Prime Bag Factory admin · {documentNumber} ·{" "}
          {new Date().toISOString().slice(0, 10)}
        </footer>
      </article>
    </main>
  );
}

/** A titled block that stays whole across page breaks. */
export function PrintSection({
  title,
  children,
}: Readonly<{ title: string; children: React.ReactNode }>) {
  return (
    <section className="break-inside-avoid">
      <h2 className="mb-2 border-b border-black/40 pb-1 text-sm font-semibold uppercase tracking-wide">
        {title}
      </h2>
      {children}
    </section>
  );
}

/** Definition-style row inside a PrintSection. */
export function PrintRow({
  label,
  children,
}: Readonly<{ label: string; children: React.ReactNode }>) {
  return (
    <div className="grid grid-cols-3 gap-2 py-0.5 text-sm">
      <dt className="text-black/70">{label}</dt>
      <dd className="col-span-2">{children ?? "—"}</dd>
    </div>
  );
}

/** Empty checkbox squares for the production checklist (print, not a form). */
export function PrintChecklist({
  items,
}: Readonly<{ items: string[] }>) {
  return (
    <ul className="space-y-1.5 text-sm">
      {items.map((item) => (
        <li key={item} className="flex items-center gap-2">
          <span
            aria-hidden="true"
            className="inline-block size-3.5 border border-black"
          />
          {item}
        </li>
      ))}
    </ul>
  );
}
